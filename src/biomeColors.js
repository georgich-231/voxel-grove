const FALLBACK_TINT = BIOME_TINTS.forest;

export function biomeGrassColor(biomeId) {
  return (BIOME_TINTS[biomeId] ?? FALLBACK_TINT).grass;
}

export function biomeFoliageColor(biomeId) {
  return (BIOME_TINTS[biomeId] ?? FALLBACK_TINT).foliage;
}

export function writePackedColor(target, index, color) {
  target[index] = (color >> 16) & 0xff;
  target[index + 1] = (color >> 8) & 0xff;
  target[index + 2] = color & 0xff;
}
